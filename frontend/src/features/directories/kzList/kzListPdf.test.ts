import { describe, expect, it } from 'vitest'
import { parseKzPages, PdfItem } from './kzListPdf'

// Элемент текста как его отдаёт pdf.js: ширина примерно по числу символов.
const t = (str: string, x: number, y: number, size = 14): PdfItem => ({ str, x, y, size, w: str.length * size * 0.5 })

describe('parseKzPages', () => {
  it('reads rows the way the EEC PDF lays them out', () => {
    const page1 = [
      t('139', 308, 793, 15),
      t('Код', 133, 715), t('Наименование позиции', 235, 707), t('Ставка ввозной', 441, 763),
      // обычная строка с номером сноски над ставкой
      t('3', 489, 261, 9),
      t('4015 12 000 9', 104, 256), t('– – – прочие', 224, 256), t('8', 482, 256),
      // код разбит на куски, ставка «10» — по цифрам
      t('44', 104, 200), t('07 96 100 3', 118, 200), t('– – прочие', 213, 200), t('1', 478, 200), t('0', 485, 200),
      // ставка в три строки, продолжение левее; двузначная сноска «15» по цифрам в конце
      t('7612 90 800 1', 104, 150), t('– – – емкости жесткие', 224, 150), t('15', 429, 150), t('или 13,2 евро за', 447, 150),
      t('цилиндрические', 225, 134), t('1000 шт в', 458, 134),
      t('1', 490, 123, 9), t('5', 494.5, 123, 9), t('зависимости, что ниже', 434, 118),
    ]
    const page2 = [
      t('9620 00 000 8', 104, 564), t('– – – из углеродных волокон', 224, 564), t('1', 480, 564), t('0', 487, 564),
      t('___________________________', 258, 514, 9),
      t('3', 85, 450, 9), t('Ставка ввозной таможенной пошлины применяется с 1 апреля 2023 г.', 93, 445),
      t('15', 85, 208, 9), t('Ставка ввозной таможенной пошлины применяется', 98, 203), t('с 1 октября 2022 г.', 85, 190),
    ]
    const page3 = [t('305', 308, 793, 15), t('22', 85, 753, 9), t('Ставка ЕТТ применяется с 1 марта 2027 г.', 98, 748), t('_____________', 85, 716)]

    const result = parseKzPages([page1, page2, page3], 'ПЕРЕЧЕНЬ РК.pdf')

    expect(result.fileName).toBe('ПЕРЕЧЕНЬ РК.pdf')
    expect(result.rows).toEqual([
      { page: 1, code: '4015120009', name: '– – – прочие', rate: '8', notes: ['3'] },
      { page: 1, code: '4407961003', name: '– – прочие', rate: '10', notes: [] },
      { page: 1, code: '7612908001', name: '– – – емкости жесткие цилиндрические', rate: '15 или 13,2 евро за 1000 шт в зависимости, что ниже', notes: ['15'] },
      { page: 2, code: '9620000008', name: '– – – из углеродных волокон', rate: '10', notes: [] },
    ])
    expect(result.footnotes).toEqual({
      3: 'Ставка ввозной таможенной пошлины применяется с 1 апреля 2023 г.',
      15: 'Ставка ввозной таможенной пошлины применяется с 1 октября 2022 г.',
      22: 'Ставка ЕТТ применяется с 1 марта 2027 г.',
    })
  })

  it('finds nothing in an unrelated document', () => {
    expect(parseKzPages([[t('Счёт на оплату', 100, 700), t('Итого 12 000', 400, 650)]]).rows).toEqual([])
  })
})
