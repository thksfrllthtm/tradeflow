// Сноски перечня, которые сотрудник проверяет сам: по коду их не отличить.
func noteFor(sectionNumber int, prefix string) string {
	const heavy = "Не применяется к транспортным средствам полной массой свыше 50 т."
	const humanitarian = "Не применяется к технике, ввозимой как гуманитарная помощь."
	switch {
	case sectionNumber == 1 && (prefix == "8704" || prefix == "8705"):
		return heavy + " " + humanitarian
	case sectionNumber == 1 && (prefix == "8702" || prefix == "8703"):
		return humanitarian
	case sectionNumber == 1 && len(prefix) > 4 && prefix[:4] == "8701":
		return heavy
	case prefix == "2710198200":
		return "Кроме моторных масел для двухтактных двигателей."
	case sectionNumber == 5 && prefix == "3820000000":
		return "Кроме омывателей стёкол."
	}
	return ""
}

