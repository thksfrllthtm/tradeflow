-- old.adilet.zan.kz отдаёт заглушку «Идут технические работы», и она сохранялась в web_pages вместо текста
-- акта (поиск по перечням общей базы переставал находить код). Чтение adilet теперь через API сайта, а
-- заглушки не сохраняются; уже сохранённые удаляются — перечни общей базы перекачает прогрев при запуске,
-- остальные акты скачаются при следующем обращении.
DELETE FROM web_pages
WHERE length(text) < 3000
  AND (text ILIKE '%идут технические работы%' OR text ILIKE '%сайт скоро возобновит%' OR title ILIKE 'технические работы%');
